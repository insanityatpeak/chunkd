package main

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/insanityatpeak/chunkd/internal/bench"
)

// report renders the charts and results.md from the CSVs under out/data.
func report(out string) error {
	data := filepath.Join(out, "data")
	charts := filepath.Join(out, "charts")
	if err := os.MkdirAll(charts, 0o755); err != nil {
		return err
	}
	read := func(name string) (*bench.Table, error) { return bench.ReadCSV(filepath.Join(data, name)) }
	write := func(name, svg string) error { return os.WriteFile(filepath.Join(charts, name), []byte(svg), 0o644) }

	var md strings.Builder
	hw, _ := os.ReadFile(filepath.Join(data, "hardware.txt"))
	md.WriteString("# Results\n\nGenerated by `go run ./tools/task bench` from the CSVs in `data/`; do not edit by hand.\n\n")
	fmt.Fprintf(&md, "Real-tier hardware: %s\n\n", strings.TrimSpace(string(hw)))
	md.WriteString("Sim-tier numbers (repair, latency, resume) are in simulated time and identical on any machine for the same seed. Real-tier numbers (throughput, real latency) are wall-clock on one machine, one client, loopback, and the OS page cache; see [README.md](README.md) for what they do and do not show.\n\n")

	section := func(title, note, csv, chart string) (*bench.Table, error) {
		t, err := read(csv)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&md, "## %s\n\n%s\n\n", title, note)
		md.WriteString(mdTable(t))
		if chart != "" {
			fmt.Fprintf(&md, "\n![%s](charts/%s)\n", title, chart)
		}
		fmt.Fprintf(&md, "\nRaw: [data/%s](data/%s)\n\n", csv, csv)
		return t, nil
	}

	// Throughput: mean of the runs per size.
	t, err := section("Throughput by file size (real, RF 3, 5 nodes)", "Put and get of one file, sequentially, 3 runs per size (1 for 1 GiB). Every chunk is checked against its hash on read.", "real-throughput.csv", "throughput.svg")
	if err != nil {
		return err
	}
	var sizes []string
	var putM, getM []float64
	for _, s := range uniq(t.Str("size_mib")) {
		sizes = append(sizes, s+" MiB")
		putM = append(putM, meanWhere(t, "size_mib", s, "put_mib_s"))
		getM = append(getM, meanWhere(t, "size_mib", s, "get_mib_s"))
	}
	if err := write("throughput.svg", bench.Bars("Throughput by file size (real, loopback, mean of runs)", "MiB/s", sizes, []bench.Series{{Name: "put", Y: putM}, {Name: "get", Y: getM}})); err != nil {
		return err
	}

	if _, err = section("Latency, real (256 KiB files, 1000 sequential operations)", "One client, no faults. The unit is milliseconds.", "real-latency.csv", ""); err != nil {
		return err
	}

	// Sim latency: get p99 by fault and hedging.
	t, err = section("Latency under a gray node and loss (sim)", "40 files of 1 MiB read 3 times, 30 puts, 3 seeds pooled, a new client for every operation (a long-lived client learns the slow node from its first reads and avoids it). Gray node: node-1 adds 2 s to every message. Loss: 1% of messages, and a lost call waits out the 10 s call timeout.", "latency.csv", "latency-get-p99.svg")
	if err != nil {
		return err
	}
	var faults []string
	var on, off []float64
	for _, f := range uniq(t.Str("fault")) {
		faults = append(faults, f)
		on = append(on, pick(t, map[string]string{"fault": f, "hedging": "on", "op": "get"}, "p99_ms"))
		off = append(off, pick(t, map[string]string{"fault": f, "hedging": "off", "op": "get"}, "p99_ms"))
	}
	if err := write("latency-get-p99.svg", bench.Bars("Get p99 latency, hedged reads on and off (sim)", "ms", faults, []bench.Series{{Name: "hedging on", Y: on}, {Name: "hedging off", Y: off}})); err != nil {
		return err
	}

	// Repair time.
	t, err = section("Time to repair after a node kill (sim)", "RF 3, 5 nodes, 4 MiB files, node-3 killed. The detector (10 s) plus the repair delay (20 s) make a 30 s floor; `past_floor_s` is what the copies add. `mib_s_past_floor` is 0 when that is under one second.", "repair-time.csv", "repair-time.svg")
	if err != nil {
		return err
	}
	vols := uniq(t.Str("volume_mib"))
	var xs []float64
	for _, v := range vols {
		f, _ := strconv.ParseFloat(v, 64)
		xs = append(xs, f)
	}
	var lines []bench.Series
	for _, lim := range uniq(t.Str("limit_mib_s")) {
		s := bench.Series{Name: lim + " MiB/s limit"}
		for _, v := range vols {
			s.Y = append(s.Y, pick(t, map[string]string{"volume_mib": v, "limit_mib_s": lim}, "whole_after_kill_s"))
		}
		lines = append(lines, s)
	}
	if err := write("repair-time.svg", bench.Lines("Time to RF 3 after a node kill (sim)", "distinct data stored (MiB)", "seconds after the kill", xs, lines, false, false)); err != nil {
		return err
	}

	// Foreground latency during repair.
	t, err = section("Repair rate cap and foreground reads (sim)", "4 MiB reads in a loop while repair copies, 3 seeds pooled, no message loss. `limit-40-mib-s` is the default; `unlimited` removes the rate limit and raises the copy slots from 8 to 64. `copy_phase_s` is how long repair took after the 30 s floor; `peak_repair_mib_s` is the highest repair copy rate over windows of a second or more. The sim gives each message its own transfer time and shares no link, disk or CPU between messages, so repair cannot slow a read here and the latencies are flat by construction. The table shows the cap holding and its cost in repair time. The effect on readers needs a real network and disks and is not measured in this run.", "repair-foreground.csv", "repair-foreground.svg")
	if err != nil {
		return err
	}
	if err := write("repair-foreground.svg", bench.Bars("Peak repair copy rate under each cap (sim)", "MiB/s", t.Str("mode"), []bench.Series{{Name: "peak repair rate", Y: t.Col("peak_repair_mib_s")}})); err != nil {
		return err
	}

	// Resume.
	t, err = section("Resumable upload cost (sim)", "A 32 MiB upload is cut off after N% (whole chunks) and finished. `resume_*`: continue at the offset the server reports. `restart_*`: a new Put of the same file, no resume. `*_finish_mib` is what crosses the network to the nodes; `*_body_mib` is what the client would send a gateway (the request body).", "resume.csv", "resume.svg")
	if err != nil {
		return err
	}
	var cuts []string
	var resBody, resWire []float64
	for i, r := range t.Str("redundancy") {
		if r != "replicate:3" {
			continue
		}
		cuts = append(cuts, t.Str("cut_at_pct")[i]+"%")
		resBody = append(resBody, t.Col("resume_body_mib")[i])
		resWire = append(resWire, t.Col("resume_finish_mib")[i])
	}
	full := make([]float64, len(cuts))
	for i := range full {
		full[i] = 32
	}
	if err := write("resume.svg", bench.Bars("Body the client re-sends after a cut-off, 32 MiB file", "MiB", cuts, []bench.Series{{Name: "restart (no resume)", Y: full}, {Name: "resume", Y: resBody}})); err != nil {
		return err
	}
	_ = resWire

	// Quota.
	t, err = section("Cost of a quota check (state machine)", "Microseconds for one Begin in the metadata state machine, by number of files in the namespace; ten other namespaces hold that many files between them. With a quota the state machine scans every file (ADR-0025).", "quota.csv", "quota.svg")
	if err != nil {
		return err
	}
	fs := uniq(t.Str("files"))
	var fx []float64
	for _, f := range fs {
		v, _ := strconv.ParseFloat(f, 64)
		fx = append(fx, v)
	}
	var qs []bench.Series
	for _, m := range []string{"no-quota", "quota"} {
		s := bench.Series{Name: m}
		for _, f := range fs {
			s.Y = append(s.Y, pick(t, map[string]string{"mode": m, "files": f}, "us_per_begin"))
		}
		qs = append(qs, s)
	}
	if err := write("quota.svg", bench.Lines("Begin cost by files in the namespace", "files in the namespace", "microseconds per Begin (log scale)", fx, qs, true, true)); err != nil {
		return err
	}

	md.WriteString("## Other measurements\n\n- Storage overhead and repair cost, replication against erasure coding: [ec.md](ec.md).\n- Dedup savings: [dedup.md](dedup.md).\n- Rebalance after adding a node: [rebalance.md](rebalance.md).\n")
	return os.WriteFile(filepath.Join(out, "results.md"), []byte(md.String()), 0o644)
}

func uniq(s []string) []string {
	var out []string
	for _, v := range s {
		if !slices.Contains(out, v) {
			out = append(out, v)
		}
	}
	return out
}

func meanWhere(t *bench.Table, key, val, col string) float64 {
	sum, n := 0.0, 0
	for i, k := range t.Str(key) {
		if k == val {
			sum += t.Col(col)[i]
			n++
		}
	}
	if n == 0 {
		return 0
	}
	return sum / float64(n)
}

// pick returns col from the first row where every key matches.
func pick(t *bench.Table, where map[string]string, col string) float64 {
rows:
	for i := range t.Rows {
		for k, v := range where {
			if t.Str(k)[i] != v {
				continue rows
			}
		}
		return t.Col(col)[i]
	}
	return 0
}

func mdTable(t *bench.Table) string {
	var b strings.Builder
	b.WriteString("| " + strings.Join(t.Header, " | ") + " |\n")
	b.WriteString("|" + strings.Repeat("---|", len(t.Header)) + "\n")
	for _, r := range t.Rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	return b.String()
}
